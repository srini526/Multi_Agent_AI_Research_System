import re
from typing import Any
from urllib.parse import urlsplit

from agent import build_reader_agent, build_search_agent, writer_chain, critic_chain
from tools import tavily_search, scrape_url


URL_RE = re.compile(r"https?://[^\s<>\"']+", re.IGNORECASE)


def _content_to_text(content: Any) -> str:
    """Convert a LangChain message/tool result to readable text."""
    if isinstance(content, str):
        return content
    if isinstance(content, list):
        parts = []
        for item in content:
            if isinstance(item, dict) and isinstance(item.get("text"), str):
                parts.append(item["text"])
            else:
                parts.append(str(item))
        return "\n".join(parts)
    return str(content or "")


def _message_attr(message: Any, name: str) -> Any:
    if isinstance(message, dict):
        return message.get(name)
    return getattr(message, name, None)


def _actual_search_tool_output(agent_result: dict) -> str:
    """Return Tavily's real tool output, not the search agent's paraphrase."""
    messages = agent_result.get("messages", [])
    outputs = []
    for message in messages:
        message_type = _message_attr(message, "type")
        tool_name = _message_attr(message, "name")
        if message_type == "tool" and tool_name in (None, "tavily_search"):
            content = _message_attr(message, "content")
            text = _content_to_text(content).strip()
            if text:
                outputs.append(text)
    return "\n\n".join(outputs)


def _parse_tavily_results(search_text: str) -> list[dict]:
    """Parse the stable Title/URL/Snippet format produced by tools.tavily_search."""
    records = []
    seen_urls = set()

    for block in re.split(r"\n-{5,}\n", search_text or ""):
        title_match = re.search(r"(?m)^Title:\s*(.*?)\s*$", block)
        url_match = re.search(r"(?m)^URL:\s*(https?://\S+)\s*$", block)
        snippet_match = re.search(r"(?m)^Snippet:\s*(.*)$", block)

        if not url_match:
            continue

        # Preserve the URL exactly as emitted by Tavily; do not rewrite it.
        url = url_match.group(1).strip()
        if url in seen_urls:
            continue

        parsed = urlsplit(url)
        if parsed.scheme not in ("http", "https") or not parsed.netloc:
            continue

        seen_urls.add(url)
        records.append({
            "id": f"S{len(records) + 1}",
            "title": title_match.group(1).strip() if title_match else "Untitled search result",
            "url": url,
            "snippet": snippet_match.group(1).strip() if snippet_match else "",
            "retrieval_status": "Not scraped",
            "page_content": "",
        })

    return records


def _scrape_source(record: dict) -> str:
    """Scrape the exact URL returned by Tavily; no LLM selects or invents it."""
    try:
        result = scrape_url.invoke({"url": record["url"]})
        text = _content_to_text(result).strip()
    except Exception as exc:
        text = f"Source URL: {record['url']}\nRetrieval status: Inaccessible\nError: {type(exc).__name__}"

    if "retrieval status: successfully retrieved" in text.lower():
        record["retrieval_status"] = "Successfully retrieved"
        record["page_content"] = text
    elif "retrieval status: inaccessible" in text.lower() or "could not scrape url" in text.lower():
        record["retrieval_status"] = "Inaccessible"
        record["page_content"] = text
    else:
        # Be conservative: a response without an explicit success status is not verified.
        record["retrieval_status"] = "Not verified"
        record["page_content"] = text or "No page content returned."

    return text


def _build_research_context(search_results: str, records: list[dict], scraped_results: str) -> str:
    parts = [
        "IMPORTANT: The following source registry was parsed from actual Tavily tool output. "
        "Source URLs and IDs are assigned by the application, not generated by the model.",
        "\nSOURCE REGISTRY:",
    ]

    if not records:
        parts.append("No parseable source URLs were returned by the Tavily search tool.")

    for record in records:
        parts.append(
            f"\n[{record['id']}]\n"
            f"Title: {record['title']}\n"
            f"Exact URL: {record['url']}\n"
            f"Search snippet: {record['snippet'] or 'No snippet returned.'}\n"
            f"Retrieval status: {record['retrieval_status']}"
        )

    parts.append("\n\nRAW TAVILY SEARCH RESULTS:\n" + (search_results or "No search results returned."))
    parts.append("\n\nACTUAL SCRAPE OUTPUT:\n" + (scraped_results or "No source pages were scraped."))
    return "\n".join(parts)


def _remove_model_sources_section(report: str) -> str:
    """Remove any model-written Sources/References list; Python replaces it."""
    pattern = re.compile(
        r"(?ims)^\s{0,3}(?:#{1,6}\s*)?(?:\d+\s*[.)]\s*)?(?:sources|references)\s*:?[ \t]*\n.*\Z"
    )
    match = pattern.search(report or "")
    if match:
        report = report[:match.start()]
    return report.strip()


def _remove_model_generated_urls(report: str) -> str:
    """Keep link labels, but remove all model-generated URL destinations from the body."""
    report = re.sub(r"\[([^\]]+)\]\(https?://[^)\s]+\)", r"\1", report or "")
    report = URL_RE.sub("", report)
    return report.strip()


def _append_trusted_sources(report: str, records: list[dict]) -> str:
    """Build the Sources section from search tool records, never from the LLM."""
    report = _remove_model_generated_urls(_remove_model_sources_section(report))
    source_lines = ["## Sources"]

    if not records:
        source_lines.append("No source URLs were returned by the search tool.")
    else:
        for record in records:
            status = record["retrieval_status"]
            title = record["title"].replace("\n", " ").strip() or "Untitled search result"
            source_lines.append(
                f"- [{record['id']}] {title} — {record['url']} (Retrieval status: {status})"
            )

    return f"{report.rstrip()}\n\n" + "\n".join(source_lines)


def run_research_pipeline(topic: str) -> dict:
    state = {}

    # Step 1: Search. Keep actual Tavily tool output so the LLM cannot invent source URLs.
    print("Step 1 - Search agent is working...........")
    search_agent = build_search_agent()
    try:
        search_agent_result = search_agent.invoke({
            "messages": [
                ("user", f"Find recent, reliable and detailed information about: {topic}. Use tavily_search.")
            ]
        })
        actual_tool_output = _actual_search_tool_output(search_agent_result)
    except Exception as exc:
        print(f"Search agent failed ({type(exc).__name__}); querying Tavily directly...")
        actual_tool_output = ""

    # If the agent did not return a ToolMessage, fall back to the actual search tool.
    # Do not use the agent's free-form answer as the source registry.
    if not actual_tool_output:
        actual_tool_output = _content_to_text(tavily_search.invoke({"query": topic}))

    state["search_results"] = actual_tool_output
    source_records = _parse_tavily_results(state["search_results"])

    # Step 2: Scrape the exact URLs from Tavily, not URLs generated by an LLM.
    print("Step 2 - Reader agent is Scraping...........")
    scraped_chunks = []
    max_sources_to_scrape = 3

    for record in source_records[:max_sources_to_scrape]:
        scraped_text = _scrape_source(record)
        scraped_chunks.append(scraped_text or f"Source URL: {record['url']}\nRetrieval status: Not verified")

    for record in source_records[max_sources_to_scrape:]:
        record["retrieval_status"] = "Not scraped (source limit)"

    state["scraped_results"] = "\n\n".join(scraped_chunks)
    research_combined = _build_research_context(
        state["search_results"], source_records, state["scraped_results"]
    )

    # Reader agent analyzes the real scraped text. It has no tools, so it cannot
    # introduce a URL that was not returned by Tavily and fetched by Python.
    reader_agent = build_reader_agent()
    reader_result = reader_agent.invoke({
        "messages": [
            ("user", """Extract concise evidence notes from this research context.
Use the existing source IDs (for example [S1]) only. Do not output URLs.
Do not add facts that are not supported by the supplied scraped content.
Clearly flag sources marked inaccessible or not scraped.

Research context:
""" + research_combined)
        ]
    })
    state["reader_analysis"] = _content_to_text(
        _message_attr(reader_result["messages"][-1], "content")
    )
    research_combined += "\n\nREADER AGENT EVIDENCE NOTES (check against the raw page content above):\n" + state["reader_analysis"]
    state["research"] = research_combined

    # Step 3: Write report. Sources are appended by Python below.
    print("Step 3 - Writer is drafting the result...........")
    draft_report = writer_chain.invoke({
        "topic": topic,
        "research": research_combined,
    })
    state["report"] = _append_trusted_sources(draft_report, source_records)

    # Step 4: Critic must compare the report to the original research.
    print("Step 4 - Critic is Reviewing the report...........")
    state["feedback"] = critic_chain.invoke({
        "research": research_combined,
        "report": state["report"],
    })

    # Additional backend metadata; existing React response fields remain unchanged.
    state["source_validation"] = {
        "source_count": len(source_records),
        "retrieved_count": sum(
            record["retrieval_status"] == "Successfully retrieved"
            for record in source_records
        ),
        "urls_from_tool_output_only": True,
    }

    return state


if __name__ == "__main__":
    topic = input("\nEnter Research Topic: ").strip()
    if topic:
        result = run_research_pipeline(topic)
        print("\nFINAL REPORT\n")
        print(result["report"])
        print("\nCRITIC FEEDBACK\n")
        print(result["feedback"])
